package net.valor.registry;

import net.minecraft.core.Registry;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.world.level.levelgen.feature.Feature;
import net.minecraft.world.level.levelgen.feature.configurations.FeatureConfiguration;
import net.valor.Valor;
import net.valor.world.level.levelgen.feature.StreamFeature;
import net.valor.world.level.levelgen.feature.TemplateTreeFeature;
import net.valor.world.level.levelgen.feature.configurations.StreamConfiguration;
import net.valor.world.level.levelgen.feature.configurations.TemplateTreeConfiguration;

/**
 * Worldgen feature types added by Valor. Counterpart to vanilla's {@link Feature} constants.
 * <p>
 * These are only the feature <i>types</i> (code). Concrete configured/placed features and the
 * biomes using them are data, generated by the worldgen datagen providers.
 */
public final class ValorFeatures {

	/** A tree built from a structure template ({@code .nbt}). */
	public static final Feature<TemplateTreeConfiguration> TEMPLATE_TREE = register("template_tree",
			new TemplateTreeFeature(TemplateTreeConfiguration.CODEC));

	/** A small, shallow, meandering stream. */
	public static final Feature<StreamConfiguration> STREAM = register("stream",
			new StreamFeature(StreamConfiguration.CODEC));

	private ValorFeatures() {}

	private static <C extends FeatureConfiguration, F extends Feature<C>> F register(String name, F feature) {
		return Registry.register(BuiltInRegistries.FEATURE, Valor.id(name), feature);
	}

	/** Forces class loading so all static fields get registered. */
	public static void init() {}
}
