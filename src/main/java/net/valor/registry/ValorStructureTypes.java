package net.valor.registry;

import com.mojang.serialization.MapCodec;
import net.minecraft.core.Registry;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.world.level.levelgen.structure.Structure;
import net.minecraft.world.level.levelgen.structure.StructureType;
import net.valor.Valor;
import net.valor.world.level.levelgen.structure.structures.RuinStructure;

/**
 * Structure types added by Valor. Counterpart to vanilla's {@link StructureType} constants.
 * <p>
 * These are only the structure <i>types</i> (code). The concrete structures, structure sets and the biome
 * tags that allow them are data, generated by the worldgen datagen providers.
 */
public final class ValorStructureTypes {

	/** A small hand-built ruin with a dig site, fitted into the terrain. */
	public static final StructureType<RuinStructure> RUIN = register("ruin", RuinStructure.CODEC);

	private ValorStructureTypes() {}

	private static <S extends Structure> StructureType<S> register(String name, MapCodec<S> codec) {
		return Registry.register(BuiltInRegistries.STRUCTURE_TYPE, Valor.id(name), () -> codec);
	}

	/** Forces class loading so all static fields get registered. */
	public static void init() {}
}
